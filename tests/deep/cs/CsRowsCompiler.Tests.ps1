# GENERATED CODE: listed, never walked - and a budget for whatever is generated without saying so
# ---------------------------------------------------------------------------------------------------

if ($script:CsRowsPython) {

Test-Case 'generated: a file that says it was generated is listed and NOT walked' {
    # Nobody asks which function reads a constant inside an EF model snapshot, and the rows are not free:
    # on one real tree nearly all of the expression rows came from `.Designer.cs` files and
    # writing them took hours. The file row stays, so the file has not silently vanished.
    $db = New-CsDb @{
        'Snapshot.cs' = '// <auto-generated />' + [char]10 +
                        'namespace Demo; public class Snapshot { public void Build() { Helper.Run("x"); } }'
        'Hand.cs'     = 'namespace Demo; public class Hand { public void Go() { Helper.Run("y"); } }'
    }
    Assert-Equal (Get-CsScalar $db "SELECT generated FROM files WHERE path = 'Snapshot.cs'") '1' 'marked generated'
    Assert-Equal (Get-CsScalar $db "SELECT count(*) FROM calls c JOIN files f ON f.id = c.file WHERE f.path = 'Snapshot.cs'") '0' 'and not walked'
    # The hand-written file beside it is untouched by the rule.
    Assert-Equal (Get-CsScalar $db "SELECT count(*) FROM calls c JOIN files f ON f.id = c.file WHERE f.path = 'Hand.cs'") '1' 'the authored file still has its rows'
}

Test-Case 'generated: the name conventions count too, marker or no marker' {
    $db = New-CsDb @{
        'Model.Designer.cs' = 'namespace Demo; public class Model { public void Build() { Helper.Run("x"); } }'
        'Parser.g.cs'       = 'namespace Demo; public class Parser { public void Build() { Helper.Run("x"); } }'
        # An authored file, so the `calls` table EXISTS to be asked about: a table that is missing entirely
        # fails the query rather than answering zero, and a case cannot tell those two apart.
        'Hand.cs'           = 'namespace Demo; public class Hand { public void Go() { Helper.Run("y"); } }'
    }
    Assert-Equal (Get-CsScalar $db "SELECT count(*) FROM files WHERE generated = 1") '2' 'both named as generated'
    Assert-Equal (Get-CsScalar $db "SELECT count(*) FROM calls c JOIN files f ON f.id = c.file WHERE f.path <> 'Hand.cs'") '0' 'neither was walked'
}

Test-Case 'generated: a folder called Migrations is NOT a generator' {
    # A folder name is a convention; a file somebody hand-wrote into it is still hand-written. The marker
    # the generator itself writes is the only thing this rule reads.
    $db = New-CsDb @{
        'Migrations/20240101_Init.cs' = 'namespace Demo; public class Init { public void Up() { Helper.Run("x"); } }'
    }
    Assert-Equal (Get-CsScalar $db "SELECT count(*) FROM files WHERE generated = 1") '0' 'not generated'
    Assert-Equal (Get-CsScalar $db 'SELECT count(*) FROM calls') '1' 'and it was walked'
}

Test-Case 'budget: a large file is walked WHOLE - there is no per-file row budget' {
    # A budget once cut a file off at 20 000 rows, and the code past the cut could not be asked about.
    $lines = New-Object System.Text.StringBuilder
    [void]$lines.AppendLine('namespace Demo; public class Big { public void Go() {')
    for ($i = 1; $i -le 6000; $i++) { [void]$lines.AppendLine("var v$i = Helper.Run($i, $i + 1);") }
    [void]$lines.AppendLine('} }')
    $db = New-CsDb @{ 'Big.cs' = $lines.ToString() }
    # 6 000 calls, 6 000 assignments and 12 000 expressions: 24 000 rows, past the old 20 000, and the last
    # rows of the file are the ones a budget dropped.
    Assert-Equal (Get-CsScalar $db "SELECT count(*) FROM calls c JOIN files f ON f.id = c.file WHERE f.path = 'Big.cs'") '6000' 'every call'
    Assert-Equal (Get-CsScalar $db "SELECT count(*) FROM expressions x JOIN files f ON f.id = x.file WHERE f.path = 'Big.cs'") '12000' 'every expression'
    Assert-Equal (Get-CsScalar $db "SELECT count(*) FROM assignments a JOIN files f ON f.id = a.file WHERE f.path = 'Big.cs'") '6000' 'every assignment'
    Assert-Equal (Get-CsScalar $db 'SELECT count(*) FROM (SELECT id FROM calls GROUP BY id HAVING count(*) > 1)') '0' 'no id handed out twice'
}

}

