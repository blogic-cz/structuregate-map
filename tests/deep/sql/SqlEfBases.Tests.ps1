    'Db/Tables.sql' = "CREATE TABLE Sales.Orders (OrderId INT NOT NULL PRIMARY KEY)`nGO`nCREATE TABLE Sales.Lines (LineId INT NOT NULL PRIMARY KEY)`n" +
        "GO`nCREATE TABLE Sales.Carts (CartId INT NOT NULL PRIMARY KEY)`n"
    'App/App.csproj' = '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net10.0</TargetFramework></PropertyGroup></Project>'
    'App/StandIns.cs' = @'
namespace Microsoft.EntityFrameworkCore.Metadata.Builders
{
    public class EntityTypeBuilder { }
    public class EntityTypeBuilder<T> where T : class { }
}
namespace Microsoft.EntityFrameworkCore
