function Invoke-SqlEfBasesMap([string]$Tree, [string[]]$Extra) {
    $run = Invoke-Gate (@('--root', $Tree, '--ext', '.cs,.sql', '--map-sqlite', (Join-Path $Tree 'links.sqlite')) + $Extra)
    Assert-Exit $run 0
    return Join-Path $Tree 'links.sqlite'
}

# `entity|schema.name|status|cls` of every `ef_table` link.
function Get-SqlEfBasesTables([string]$Db) {
    $r = Invoke-Gate --map-query $Db --width 0 --limit 0 --sql ("SELECT 'v=' || entity || '|' || schema || '.' || name || '|' || status || '|' || cls " +
        "FROM sql_links WHERE kind = 'ef_table' ORDER BY entity")
    Assert-Exit $r 0
    return @($r.Lines | Where-Object { $_.TrimStart().StartsWith('v=') } | ForEach-Object { $_.Trim().Substring(2) })
}

Test-Case 'sqlefbases: a base configuration reading its constructor links once per derived class that fixes the name (#141)' {
    $tree = Use-Tree $script:SqlEfBasesFiles
    $tables = Get-SqlEfBasesTables (Invoke-SqlEfBasesMap $tree @())
    $want = @('Demo.Line|Sales.Lines|bound|LineConfig', 'Demo.Order|Sales.Orders|bound|OrderConfig')
    if (($tables -join "`n") -ne ($want -join "`n")) { throw "ef_table links:`nexpected:`n$($want -join "`n")`ngot:`n$($tables -join "`n")" }
}

Test-Case 'sqlefbases: a model snapshot links its tables only when --map-include-generated names it, and toggling re-reads it (#140)' {
    $tree = Use-Tree $script:SqlEfBasesFiles
    $db = Invoke-SqlEfBasesMap $tree @()
    if ((Get-SqlEfBasesTables $db) -like 'Demo.Cart|*') { throw 'a generated snapshot linked a table without being named' }
    $db = Invoke-SqlEfBasesMap $tree @('--map-include-generated', '**/*ModelSnapshot.cs')
    if (@(Get-SqlEfBasesTables $db) -notcontains 'Demo.Cart|Sales.Carts|bound|ShopContextModelSnapshot') {
        throw "the named snapshot has no ef_table link: $((Get-SqlEfBasesTables $db) -join ', ')"
    }
    $file = Invoke-Gate --map-query $db --width 0 --sql "SELECT 'v=' || generated FROM files WHERE path GLOB '*ModelSnapshot.cs'"
    Assert-Line $file 'v=1'
    $db = Invoke-SqlEfBasesMap $tree @()
    if ((Get-SqlEfBasesTables $db) -like 'Demo.Cart|*') { throw 'the snapshot kept its rows after the glob was dropped' }
}
