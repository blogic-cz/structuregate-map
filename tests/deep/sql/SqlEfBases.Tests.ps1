public abstract class ConfigBase<TEntity>(string tableName, string schemaName) : IEntityTypeConfiguration<TEntity> where TEntity : class
{
    public virtual void Configure(EntityTypeBuilder<TEntity> builder) => builder.ToTable(tableName, schemaName);
}

public class OrderConfig() : ConfigBase<Order>(Tables.Orders, Schemas.Sales);

public abstract class ClassicBase<TEntity> : IEntityTypeConfiguration<TEntity> where TEntity : class
{
    private readonly string table;
    protected ClassicBase(string table) { this.table = table; }
    public void Configure(EntityTypeBuilder<TEntity> builder) => builder.ToTable(table, "Sales");
}

public class LineConfig : ClassicBase<Line>
{
    public LineConfig() : base(Tables.Lines) { }
}
