<#
    WHERE AN EF MAPPING'S TABLE NAME COMES FROM WHEN THE `ToTable` CALL DOES NOT SPELL IT (`src/Map/Sql/SqlLinksEf.cs`):
    - #141: a generic base configuration calls `ToTable(tableName, schemaName)` with its constructor's parameters - a primary
      constructor's, or fields a constructor sets from them - and each derived class fixes them in its base call
      (`OrderConfig() : ConfigBase<Order>(Tables.Orders, Schemas.Sales)`, `: base(..)`): one `ef_table` per derived class, for the
      entity it closes `TEntity` with, and no `unknown` link at the base;
    - #140: an EF model snapshot is generated (`// <auto-generated />`) and gets no rows, unless `--map-include-generated` names it;
      then its `b.ToTable(..)` links, for the entity `modelBuilder.Entity("Demo.Order", b => ..)` spells.

    Its helpers are its own - `-Only SqlEfBases` runs this suite alone.
#>

